import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {initProject,selectFramework,readJson} from '../lib/core.mjs';
import {applyFactory,factoryPlan} from '../lib/factory.mjs';
import {skillPlan} from '../lib/skills.mjs';

const py=process.platform==='win32'?'python':'python3';
function repository(t){
 const root=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'pinit-orchestration-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const r=spawnSync('git',['init','-q'],{cwd:root,encoding:'utf8'});assert.equal(r.status,0,r.stderr);
 initProject(root,{mode:'Existing',ui:'no',intent:'automation'});selectFramework(root,'none');
 return root;
}
const configFile=root=>path.join(root,'.claude/skills/factory/config.json');

test('the Factory orchestrator defaults to Claude and can be switched to Codex',t=>{
 const root=repository(t);
 const installed=applyFactory(root,{apply:true});
 assert.equal(installed.orchestrator.current,'claude');
 assert.equal(readJson(configFile(root)).orchestrator,'claude');
 assert.ok(fs.existsSync(path.join(root,'.agents/skills/factory/SKILL.md')),'Codex has the orchestrator skill too');
 assert.match(fs.readFileSync(path.join(root,'.agents/skills/factory/SKILL.md'),'utf8'),/If it is not `codex`, stop/);
 assert.match(fs.readFileSync(path.join(root,'.claude/skills/factory/SKILL.md'),'utf8'),/If it is `codex`, stop/);
 assert.ok(fs.existsSync(path.join(root,'.claude/skills/factory/scripts/claude_worker.py')));
 const switched=applyFactory(root,{apply:true,orchestrator:'codex'});
 assert.deepEqual(switched.orchestratorSetting,{action:'set',orchestrator:'codex',previous:'claude'});
 assert.equal(switched.orchestrator.current,'codex');
 const status=spawnSync(py,[path.join(root,'.claude/skills/factory/scripts/board.py'),'status'],{cwd:root,encoding:'utf8'});
 assert.equal(status.status,0,status.stderr);assert.match(status.stdout,/^orchestrator=codex$/m);
 assert.equal(applyFactory(root,{apply:true}).orchestrator.current,'codex','re-applying without a choice keeps the configured orchestrator');
 assert.throws(()=>factoryPlan(root,{orchestrator:'gemini'}),/claude or codex/);
});

test('updating an existing Factory config adds new settings without overwriting choices',t=>{
 const root=repository(t);applyFactory(root,{apply:true});
 const config=readJson(configFile(root));delete config.orchestrator;delete config.claude;config.max_fix_rounds=5;
 fs.writeFileSync(configFile(root),JSON.stringify(config,null,2));
 const again=applyFactory(root,{apply:true});
 assert.deepEqual(again.configMigration,{action:'added-defaults',added:['orchestrator','claude']});
 const after=readJson(configFile(root));
 assert.equal(after.orchestrator,'claude');assert.equal(after.max_fix_rounds,5);assert.deepEqual(after.claude.args,['--permission-mode','acceptEdits']);
 assert.equal(applyFactory(root,{apply:true}).configMigration.action,'current');
});

test('user-scope wiring keeps one managed rules block per agent and preserves the user’s own instructions',t=>{
 const root=repository(t),home=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'pinit-home-'));
 t.after(()=>fs.rmSync(home,{recursive:true,force:true}));
 const claudeRules=path.join(home,'.claude','CLAUDE.md'),codexRules=path.join(home,'.codex','AGENTS.md');
 fs.mkdirSync(path.dirname(claudeRules),{recursive:true});fs.writeFileSync(claudeRules,'My own rule\n');
 const preview=skillPlan(root,{scope:'user',userHome:home});
 assert.deepEqual(preview.rules.map(item=>[item.agent,item.action]),[['codex','create'],['claude','append']]);
 assert.equal(fs.existsSync(codexRules),false,'preview writes nothing');
 skillPlan(root,{scope:'user',userHome:home,apply:true});
 const claudeText=fs.readFileSync(claudeRules,'utf8');
 assert.ok(claudeText.startsWith('My own rule\n'));
 assert.equal(claudeText.split('project-init:agent-rules:start').length,2);
 assert.match(claudeText,/project-init status --project \./);
 assert.match(fs.readFileSync(codexRules,'utf8'),/Only the configured orchestrator/);
 assert.deepEqual(skillPlan(root,{scope:'user',userHome:home}).rules.map(item=>item.action),['unchanged','unchanged']);
 fs.writeFileSync(claudeRules,claudeText.replace('Report actual test','OLD WORDING')+'Trailing note\n');
 skillPlan(root,{scope:'user',userHome:home,apply:true});
 const refreshed=fs.readFileSync(claudeRules,'utf8');
 assert.ok(refreshed.startsWith('My own rule\n'));assert.ok(refreshed.endsWith('Trailing note\n'));
 assert.equal(refreshed.includes('OLD WORDING'),false);assert.equal(refreshed.split('project-init:agent-rules:start').length,2);
 assert.deepEqual(skillPlan(root,{scope:'project'}).rules,[],'project scope never edits agent instruction files');
});

test('skills generated by an earlier Project Init update in place while hand-written skills stay protected',t=>{
 const root=repository(t),home=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'pinit-home-'));
 t.after(()=>fs.rmSync(home,{recursive:true,force:true}));
 skillPlan(root,{scope:'user',userHome:home,apply:true});
 const generated=path.join(home,'.claude/skills/project-init-design/SKILL.md'),current=fs.readFileSync(generated,'utf8');
 fs.writeFileSync(generated,current.replace(/If `project-init status`[^\n]*/,'Earlier preamble without the worktree rule.'));
 const plan=skillPlan(root,{scope:'user',userHome:home});
 assert.equal(plan.skills.find(item=>item.path==='.claude/skills/project-init-design/SKILL.md').action,'update');
 const applied=skillPlan(root,{scope:'user',userHome:home,apply:true});
 assert.equal(applied.updated,1);assert.equal(fs.readFileSync(generated,'utf8'),current);
 const custom=path.join(home,'.claude/skills/project-init-plan/SKILL.md');fs.writeFileSync(custom,'MY OWN PLAN SKILL');
 assert.equal(skillPlan(root,{scope:'user',userHome:home}).skills.find(item=>item.path==='.claude/skills/project-init-plan/SKILL.md').action,'conflict');
 assert.throws(()=>skillPlan(root,{scope:'user',userHome:home,apply:true}),/Existing skill content differs/);
 assert.equal(fs.readFileSync(custom,'utf8'),'MY OWN PLAN SKILL');
});
